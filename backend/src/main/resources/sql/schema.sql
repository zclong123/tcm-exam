-- ============================================================
-- 中医考试系统 数据库建表脚本 (PostgreSQL 16)
-- 运行顺序：schema.sql -> seed_basic.sql -> seed_questions.sql
-- ============================================================

CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ---------- 用户与组织 ----------
CREATE TABLE IF NOT EXISTS sys_user (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username    VARCHAR(50)  NOT NULL UNIQUE,
    password    VARCHAR(100) NOT NULL,
    real_name   VARCHAR(50),
    email       VARCHAR(100),
    phone       VARCHAR(20),
    avatar      VARCHAR(255),
    clazz_id    BIGINT,
    role_code   VARCHAR(30)  NOT NULL DEFAULT 'STUDENT', -- STUDENT/TEACHER/ADMIN
    status      SMALLINT     NOT NULL DEFAULT 1,
    created_at  TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at  TIMESTAMP    NOT NULL DEFAULT now(),
    deleted_at  TIMESTAMP
);
COMMENT ON TABLE sys_user IS '系统用户';

CREATE TABLE IF NOT EXISTS department (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE,
    created_at  TIMESTAMP NOT NULL DEFAULT now()
);
COMMENT ON TABLE department IS '院系';

CREATE TABLE IF NOT EXISTS clazz (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    department_id BIGINT REFERENCES department(id),
    grade         VARCHAR(20),
    created_at    TIMESTAMP NOT NULL DEFAULT now()
);
COMMENT ON TABLE clazz IS '班级';

CREATE TABLE IF NOT EXISTS sys_role (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(30) NOT NULL UNIQUE,
    name        VARCHAR(50) NOT NULL,
    description VARCHAR(200)
);
COMMENT ON TABLE sys_role IS '角色';

CREATE TABLE IF NOT EXISTS sys_permission (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(50) NOT NULL UNIQUE,
    name        VARCHAR(50) NOT NULL,
    type        VARCHAR(20)  DEFAULT 'API',
    created_at  TIMESTAMP NOT NULL DEFAULT now()
);
COMMENT ON TABLE sys_permission IS '权限';

CREATE TABLE IF NOT EXISTS sys_user_role (
    user_id BIGINT NOT NULL REFERENCES sys_user(id),
    role_id BIGINT NOT NULL REFERENCES sys_role(id),
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE IF NOT EXISTS sys_role_permission (
    role_id       BIGINT NOT NULL REFERENCES sys_role(id),
    permission_id BIGINT NOT NULL REFERENCES sys_permission(id),
    PRIMARY KEY (role_id, permission_id)
);

-- ---------- 知识体系 ----------
CREATE TABLE IF NOT EXISTS subject (
    id          BIGINT PRIMARY KEY,
    name        VARCHAR(50) NOT NULL UNIQUE,
    sort        INT DEFAULT 0,
    created_at  TIMESTAMP NOT NULL DEFAULT now()
);
COMMENT ON TABLE subject IS '学科（中医基础理论/诊断学/中药学/方剂学/针灸学/内科学）';

CREATE TABLE IF NOT EXISTS knowledge_point (
    id          BIGINT PRIMARY KEY,
    subject_id  BIGINT NOT NULL REFERENCES subject(id),
    name        VARCHAR(100) NOT NULL,
    parent_id   BIGINT REFERENCES knowledge_point(id),
    created_at  TIMESTAMP NOT NULL DEFAULT now()
);
COMMENT ON TABLE knowledge_point IS '知识点（层级树）';

-- ---------- 题库 ----------
CREATE TABLE IF NOT EXISTS question (
    id                BIGINT PRIMARY KEY,
    subject_id        BIGINT NOT NULL REFERENCES subject(id),
    knowledge_point_id BIGINT REFERENCES knowledge_point(id),
    qtype             VARCHAR(20) NOT NULL,  -- A/X/判断/填空/B/名解/简答/论述/病案
    difficulty        SMALLINT NOT NULL DEFAULT 2, -- 1-5
    cognitive_level   VARCHAR(10) DEFAULT '记忆',  -- 记忆/理解/应用/分析
    stem              TEXT NOT NULL,
    score             NUMERIC(6,1) DEFAULT 1.0,
    status            SMALLINT NOT NULL DEFAULT 0, -- 0待审/1通过/2驳回
    audit_remark      VARCHAR(255),
    created_by        BIGINT,
    created_at        TIMESTAMP NOT NULL DEFAULT now(),
    updated_at        TIMESTAMP NOT NULL DEFAULT now(),
    deleted_at        TIMESTAMP
);
COMMENT ON TABLE question IS '试题';

CREATE TABLE IF NOT EXISTS question_option (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id BIGINT NOT NULL REFERENCES question(id),
    option_key  VARCHAR(10) NOT NULL,
    option_text TEXT NOT NULL,
    is_correct  SMALLINT NOT NULL DEFAULT 0
);
COMMENT ON TABLE question_option IS '题目选项';

CREATE TABLE IF NOT EXISTS question_answer (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id  BIGINT NOT NULL REFERENCES question(id),
    answer_type  VARCHAR(20) NOT NULL,  -- A/X/判断/填空/B/名解...
    answer_text  TEXT NOT NULL
);
COMMENT ON TABLE question_answer IS '题目标准答案';

CREATE TABLE IF NOT EXISTS question_analysis (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id   BIGINT NOT NULL REFERENCES question(id),
    analysis_text TEXT
);
COMMENT ON TABLE question_analysis IS '题目解析';

CREATE TABLE IF NOT EXISTS question_knowledge (
    question_id BIGINT NOT NULL REFERENCES question(id),
    knowledge_point_id BIGINT NOT NULL REFERENCES knowledge_point(id),
    PRIMARY KEY (question_id, knowledge_point_id)
);

-- ---------- 试卷 ----------
CREATE TABLE IF NOT EXISTS paper (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(200) NOT NULL,
    paper_type  VARCHAR(20) NOT NULL DEFAULT 'SMART', -- SMART智能/MANUAL手工
    total_score NUMERIC(6,1) DEFAULT 100,
    question_count INT DEFAULT 0,
    subject_id  BIGINT,
    difficulty  SMALLINT DEFAULT 2,
    rule_json   TEXT,
    created_by  BIGINT,
    status      SMALLINT DEFAULT 0, -- 0草稿/1已发布
    created_at  TIMESTAMP NOT NULL DEFAULT now(),
    updated_at  TIMESTAMP NOT NULL DEFAULT now()
);
COMMENT ON TABLE paper IS '试卷';

CREATE TABLE IF NOT EXISTS paper_question (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paper_id    BIGINT NOT NULL REFERENCES paper(id),
    question_id BIGINT NOT NULL REFERENCES question(id),
    sort        INT DEFAULT 0,
    score       NUMERIC(6,1) DEFAULT 1.0
);
COMMENT ON TABLE paper_question IS '试卷题目';

CREATE TABLE IF NOT EXISTS paper_template (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(200) NOT NULL,
    subject_id  BIGINT,
    rule_json   TEXT,
    created_by  BIGINT,
    created_at  TIMESTAMP NOT NULL DEFAULT now()
);
COMMENT ON TABLE paper_template IS '组卷模板';

-- ---------- 考试 ----------
CREATE TABLE IF NOT EXISTS exam (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(200) NOT NULL,
    paper_id      BIGINT NOT NULL REFERENCES paper(id),
    clazz_id      BIGINT,
    start_time    TIMESTAMP,
    end_time      TIMESTAMP,
    duration_min  INT DEFAULT 90,
    pass_score    NUMERIC(6,1) DEFAULT 60,
    shuffle       BOOLEAN DEFAULT TRUE,   -- 题目/选项乱序
    anti_cheat    BOOLEAN DEFAULT TRUE,   -- 防切屏
    switch_limit  INT DEFAULT 3,          -- 允许切屏次数
    status        SMALLINT DEFAULT 0,     -- 0未开始/1进行中/2已结束/3草稿
    created_by    BIGINT,
    created_at    TIMESTAMP NOT NULL DEFAULT now(),
    updated_at    TIMESTAMP NOT NULL DEFAULT now()
);
COMMENT ON TABLE exam IS '考试场次';

-- ---------- 答题 ----------
CREATE TABLE IF NOT EXISTS exam_record (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id       BIGINT REFERENCES exam(id),   -- 随机组卷练习可为空
    student_id    BIGINT NOT NULL REFERENCES sys_user(id),
    paper_snapshot TEXT,
    start_time    TIMESTAMP DEFAULT now(),
    submit_time   TIMESTAMP,
    total_score   NUMERIC(8,2),
    status        VARCHAR(20) DEFAULT 'ING', -- ING进行中/SUBMITTED已提交/AUTO自动交卷/GRADED已判分
    switch_count  INT DEFAULT 0,
    ip            VARCHAR(50),
    created_at    TIMESTAMP NOT NULL DEFAULT now()
);
COMMENT ON TABLE exam_record IS '学生考试记录';

CREATE TABLE IF NOT EXISTS exam_answer (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_id     BIGINT NOT NULL REFERENCES exam_record(id),
    question_id   BIGINT NOT NULL REFERENCES question(id),
    student_answer TEXT,
    is_marked     BOOLEAN DEFAULT FALSE,   -- 答题卡标记
    is_correct    BOOLEAN,
    score         NUMERIC(6,1),
    review_status VARCHAR(10) DEFAULT 'NONE', -- NONE/AUTO/REVIEWED
    review_comment TEXT,
    reviewed_by   BIGINT,
    reviewed_at   TIMESTAMP,
    created_at    TIMESTAMP NOT NULL DEFAULT now(),
    updated_at    TIMESTAMP NOT NULL DEFAULT now(),
    UNIQUE (record_id, question_id)
);
COMMENT ON TABLE exam_answer IS '每题作答与判分';

-- ---------- 成绩 ----------
CREATE TABLE IF NOT EXISTS score (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id       BIGINT REFERENCES exam(id),   -- 随机组卷练习可为空
    student_id    BIGINT NOT NULL REFERENCES sys_user(id),
    record_id     BIGINT NOT NULL REFERENCES exam_record(id),
    total_score   NUMERIC(8,2) NOT NULL,
    is_pass       BOOLEAN NOT NULL DEFAULT FALSE,
    rank_no       INT,
    created_at    TIMESTAMP NOT NULL DEFAULT now(),
    UNIQUE (record_id)
);
COMMENT ON TABLE score IS '成绩';

-- ---------- 错题本 ----------
CREATE TABLE IF NOT EXISTS wrong_question (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id    BIGINT NOT NULL REFERENCES sys_user(id),
    question_id   BIGINT NOT NULL REFERENCES question(id),
    source_type   VARCHAR(20) DEFAULT 'EXAM',
    source_exam_id BIGINT,
    wrong_times   INT DEFAULT 1,
    mastered      BOOLEAN DEFAULT FALSE,
    review_interval INT DEFAULT 1,  -- 间隔复习天数
    last_review_at TIMESTAMP,
    created_at    TIMESTAMP NOT NULL DEFAULT now(),
    updated_at    TIMESTAMP NOT NULL DEFAULT now(),
    UNIQUE (student_id, question_id)
);
COMMENT ON TABLE wrong_question IS '错题本';

-- ---------- 统计 ----------
CREATE TABLE IF NOT EXISTS question_stat (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id   BIGINT NOT NULL UNIQUE REFERENCES question(id),
    answer_count  INT DEFAULT 0,
    correct_count INT DEFAULT 0,
    correct_rate  NUMERIC(6,4),
    difficulty_real NUMERIC(6,4),
    discrimination NUMERIC(6,4),
    updated_at    TIMESTAMP NOT NULL DEFAULT now()
);
COMMENT ON TABLE question_stat IS '题目统计（难度/区分度）';

-- ---------- 审计 ----------
CREATE TABLE IF NOT EXISTS audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT,
    action      VARCHAR(100),
    method      VARCHAR(10),
    path        VARCHAR(200),
    params      TEXT,
    ip          VARCHAR(50),
    created_at  TIMESTAMP NOT NULL DEFAULT now()
);
COMMENT ON TABLE audit_log IS '操作审计日志';

-- ---------- 索引 ----------
CREATE INDEX IF NOT EXISTS idx_question_subject ON question(subject_id);
CREATE INDEX IF NOT EXISTS idx_question_type ON question(qtype);
CREATE INDEX IF NOT EXISTS idx_question_diff ON question(difficulty);
CREATE INDEX IF NOT EXISTS idx_question_status ON question(status);
CREATE INDEX IF NOT EXISTS idx_option_question ON question_option(question_id);
CREATE INDEX IF NOT EXISTS idx_answer_question ON question_answer(question_id);
CREATE INDEX IF NOT EXISTS idx_analysis_question ON question_analysis(question_id);
CREATE INDEX IF NOT EXISTS idx_paper_q_paper ON paper_question(paper_id);
CREATE INDEX IF NOT EXISTS idx_exam_paper ON exam(paper_id);
CREATE INDEX IF NOT EXISTS idx_record_exam ON exam_record(exam_id);
CREATE INDEX IF NOT EXISTS idx_record_student ON exam_record(student_id);
CREATE INDEX IF NOT EXISTS idx_answer_record ON exam_answer(record_id);
CREATE INDEX IF NOT EXISTS idx_score_exam ON score(exam_id);
CREATE INDEX IF NOT EXISTS idx_score_student ON score(student_id);
CREATE INDEX IF NOT EXISTS idx_wrong_student ON wrong_question(student_id);
CREATE INDEX IF NOT EXISTS idx_kp_subject ON knowledge_point(subject_id);
